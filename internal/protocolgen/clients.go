package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"strings"
)

// The client type files are rendered from the schema document, so they
// describe exactly what the schema does.

const generatedHeader = "Code generated by protocolgen from cmd/agentd/protocol.schema.json; DO NOT EDIT."

// tsMapNames and pyMapNames are the names the client files declare
// besides the definitions; a definition must not take one of them.
var (
	tsMapNames = []string{"ProtocolVersion", "Methods", "Notifications", "ClientNotifications", "ReverseRequests", "Event", "Events"}
	pyMapNames = []string{"MethodName", "NotificationName", "ClientNotificationName", "ReverseRequestName", "EventType", "Events"}
)

var identifierPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

var pythonKeywords = []string{
	"False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
	"def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in",
	"is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
}

// typeIdentifier turns a $defs name such as agent.Config into a type name
// such as AgentConfig.
func typeIdentifier(defName string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(defName, ".") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// decodeSchema parses the schema and checks that every definition gets a
// distinct identifier that no generated declaration uses.
func decodeSchema(raw []byte, reserved []string) (map[string]any, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var doc map[string]any
	if err := dec.Decode(&doc); err != nil {
		return nil, err
	}
	seen := map[string]string{}
	for _, name := range reserved {
		seen[name] = "a generated declaration"
	}
	for _, name := range slices.Sorted(maps.Keys(object(doc["$defs"]))) {
		id := typeIdentifier(name)
		if !identifierPattern.MatchString(id) {
			return nil, fmt.Errorf("$defs %q has no valid identifier", name)
		}
		if other, ok := seen[id]; ok {
			return nil, fmt.Errorf("$defs %q and %s both become %s", name, other, id)
		}
		seen[id] = fmt.Sprintf("$defs %q", name)
	}
	return doc, nil
}

func object(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

func sortedKeys(v any) []string { return slices.Sorted(maps.Keys(object(v))) }

func quote(s string) string {
	data, _ := json.Marshal(s)
	return string(data)
}

func refName(s map[string]any) (string, bool) {
	r, ok := s["$ref"].(string)
	if !ok {
		return "", false
	}
	return typeIdentifier(strings.TrimPrefix(r, "#/$defs/")), true
}

func examples(s map[string]any) []string {
	var out []string
	for _, v := range s["examples"].([]any) {
		out = append(out, quote(v.(string)))
	}
	return out
}

// typescriptTypes renders the schema as TypeScript declarations that
// Node's type stripping can erase: interfaces and type aliases only.
func typescriptTypes(raw []byte) ([]byte, error) {
	doc, err := decodeSchema(raw, tsMapNames)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// " + generatedHeader + "\n\n")
	tsComment(&b, "", fmt.Sprint(doc["description"]))
	fmt.Fprintf(&b, "export type ProtocolVersion = %s;\n", doc["protocolVersion"])

	defs := object(doc["$defs"])
	for _, name := range sortedKeys(defs) {
		def := object(defs[name])
		b.WriteString("\n")
		tsComment(&b, "", fmt.Sprint(name, " in Go."))
		id := typeIdentifier(name)
		if props, ok := def["properties"]; ok {
			b.WriteString("export interface " + id + " " + tsObject(object(props), "") + "\n")
		} else {
			b.WriteString("export type " + id + " = " + tsType(def, "") + ";\n")
		}
	}

	sections := []struct{ key, name, doc string }{
		{"methods", "Methods", "Client requests, by method, with their params and result."},
		{"notifications", "Notifications", "Notifications agentd sends, by method."},
		{"clientNotifications", "ClientNotifications", "Notifications the client sends, by method."},
		{"reverseRequests", "ReverseRequests", "Requests agentd sends to the client, by method; the client replies with the result."},
	}
	for _, section := range sections {
		entries := object(doc[section.key])
		b.WriteString("\n")
		tsComment(&b, "", section.doc)
		b.WriteString("export interface " + section.name + " {\n")
		for _, method := range sortedKeys(entries) {
			entry := object(entries[method])
			fmt.Fprintf(&b, "  %s: { params: %s", quote(method), tsType(object(entry["params"]), "  "))
			if result, ok := entry["result"]; ok {
				fmt.Fprintf(&b, "; result: %s", tsType(object(result), "  "))
			}
			b.WriteString(" };\n")
		}
		b.WriteString("}\n")
	}

	events := object(doc["events"])
	b.WriteString("\n")
	tsComment(&b, "", "The event types an EventNotification carries, by its Type.")
	b.WriteString("export interface Events {\n")
	for _, name := range sortedKeys(events) {
		fmt.Fprintf(&b, "  %s: %s;\n", name, tsType(object(events[name]), "  "))
	}
	b.WriteString("}\n\n")
	tsComment(&b, "", "An EventNotification's Type with the Event it carries.")
	b.WriteString("export type Event =\n")
	for _, name := range sortedKeys(events) {
		fmt.Fprintf(&b, "  | { Type: %s; Event: %s }\n", quote(name), tsType(object(events[name]), "  "))
	}
	b.WriteString(";\n")
	return []byte(b.String()), nil
}

func tsComment(b *strings.Builder, indent, text string) {
	text = strings.ReplaceAll(text, "*/", "*\\/")
	b.WriteString(indent + "/** " + text + " */\n")
}

func tsObject(props map[string]any, indent string) string {
	if len(props) == 0 {
		return "{}"
	}
	var b strings.Builder
	b.WriteString("{\n")
	for _, key := range sortedKeys(props) {
		prop := object(props[key])
		if d := propertyDoc(prop); d != "" {
			tsComment(&b, indent+"  ", d)
		}
		name := key
		if !identifierPattern.MatchString(key) {
			name = quote(key)
		}
		fmt.Fprintf(&b, "%s  %s?: %s;\n", indent, name, tsType(prop, indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}

func tsType(s map[string]any, indent string) string {
	if id, ok := refName(s); ok {
		return id
	}
	if options, ok := s["anyOf"].([]any); ok {
		var parts []string
		for _, option := range options {
			parts = append(parts, tsType(object(option), indent))
		}
		return strings.Join(parts, " | ")
	}
	switch s["type"] {
	case "null":
		return "null"
	case "string":
		if _, ok := s["examples"]; ok {
			return strings.Join(examples(s), " | ") + " | (string & {})"
		}
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return "Array<" + tsType(object(s["items"]), indent) + ">"
	case "object":
		if props, ok := s["properties"]; ok {
			return tsObject(object(props), indent)
		}
		if additional, ok := s["additionalProperties"]; ok {
			return "{ [key: string]: " + tsType(object(additional), indent) + " }"
		}
		if s["maxProperties"] != nil {
			return "Record<string, never>"
		}
		return "{ [key: string]: unknown }"
	}
	return "unknown"
}

// pythonTypes renders the schema as Python 3.11 typing declarations:
// TypedDicts, Literal unions, and aliases, with no other imports.
func pythonTypes(raw []byte) ([]byte, error) {
	doc, err := decodeSchema(raw, pyMapNames)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "PROTOCOL_VERSION = %s\n", doc["protocolVersion"])

	defs := object(doc["$defs"])
	for _, name := range sortedKeys(defs) {
		def := object(defs[name])
		id := typeIdentifier(name)
		b.WriteString("\n\n# " + name + " in Go.\n")
		props, isObject := def["properties"]
		switch {
		case !isObject:
			b.WriteString(id + " = " + pyType(def, true) + "\n")
		case slices.ContainsFunc(sortedKeys(props), func(key string) bool {
			return !identifierPattern.MatchString(key) || slices.Contains(pythonKeywords, key)
		}):
			// Some names cannot be class attributes, so the functional
			// form names every field with a string.
			b.WriteString(id + " = TypedDict(\n    " + quote(id) + ",\n    {\n")
			for _, key := range sortedKeys(props) {
				prop := object(object(props)[key])
				pyComment(&b, "        ", prop)
				fmt.Fprintf(&b, "        %s: %s,\n", quote(key), pyType(prop, true))
			}
			b.WriteString("    },\n    total=False,\n)\n")
		default:
			b.WriteString("class " + id + "(TypedDict, total=False):\n")
			if len(object(props)) == 0 {
				b.WriteString("    pass\n")
			}
			for _, key := range sortedKeys(props) {
				prop := object(object(props)[key])
				pyComment(&b, "    ", prop)
				fmt.Fprintf(&b, "    %s: %s\n", key, pyType(prop, false))
			}
		}
	}

	for _, section := range []struct{ key, name string }{
		{"methods", "MethodName"},
		{"notifications", "NotificationName"},
		{"clientNotifications", "ClientNotificationName"},
		{"reverseRequests", "ReverseRequestName"},
		{"events", "EventType"},
	} {
		b.WriteString("\n" + section.name + " = Literal[\n")
		for _, name := range sortedKeys(doc[section.key]) {
			b.WriteString("    " + quote(name) + ",\n")
		}
		b.WriteString("]\n")
	}
	events := object(doc["events"])
	b.WriteString("\n# The event types an EventNotification carries, by its Type.\nEvents = TypedDict(\n    \"Events\",\n    {\n")
	for _, name := range sortedKeys(events) {
		fmt.Fprintf(&b, "        %s: %s,\n", quote(name), pyType(object(events[name]), true))
	}
	b.WriteString("    },\n    total=False,\n)\n")

	body := b.String()
	var imports []string
	for _, name := range []string{"Any", "Literal", "Optional", "TypedDict", "Union"} {
		if regexp.MustCompile(`\b` + name + `\b`).MatchString(body) {
			imports = append(imports, name)
		}
	}
	if len(imports) == 0 {
		return nil, errors.New("python types use nothing from typing")
	}
	var out strings.Builder
	out.WriteString("# " + generatedHeader + "\n")
	out.WriteString("\"\"\"Types of the agentd protocol.\n\n" + fmt.Sprint(doc["description"]) + "\n\"\"\"\n\n")
	out.WriteString("from __future__ import annotations\n\n")
	out.WriteString("from typing import " + strings.Join(imports, ", ") + "\n\n")
	out.WriteString(body)
	return []byte(out.String()), nil
}

// propertyDoc returns the description of a property, or notes that its
// string holds base64.
func propertyDoc(prop map[string]any) string {
	if d, ok := prop["description"].(string); ok {
		return d
	}
	options, _ := prop["anyOf"].([]any)
	for _, s := range append(options, prop) {
		if object(s)["contentEncoding"] == "base64" {
			return "base64"
		}
	}
	return ""
}

func pyComment(b *strings.Builder, indent string, prop map[string]any) {
	if d := propertyDoc(prop); d != "" {
		b.WriteString(indent + "# " + d + "\n")
	}
}

// pyType renders s as a Python annotation. Eager annotations are
// evaluated when the module loads, so they quote definition names and
// avoid | on strings; lazy ones are class annotations, which
// `from __future__ import annotations` leaves unevaluated.
func pyType(s map[string]any, eager bool) string {
	if id, ok := refName(s); ok {
		if eager {
			return quote(id)
		}
		return id
	}
	if options, ok := s["anyOf"].([]any); ok {
		var parts []string
		hasNull := false
		for _, option := range options {
			if object(option)["type"] == "null" {
				hasNull = true
				continue
			}
			parts = append(parts, pyType(object(option), eager))
		}
		if !eager {
			if hasNull {
				parts = append(parts, "None")
			}
			return strings.Join(parts, " | ")
		}
		inner := parts[0]
		if len(parts) > 1 {
			inner = "Union[" + strings.Join(parts, ", ") + "]"
		}
		if hasNull {
			return "Optional[" + inner + "]"
		}
		return inner
	}
	switch s["type"] {
	case "null":
		return "None"
	case "string":
		if _, ok := s["examples"]; ok {
			return "Literal[" + strings.Join(examples(s), ", ") + "] | str"
		}
		return "str"
	case "integer":
		return "int"
	case "number":
		return "float"
	case "boolean":
		return "bool"
	case "array":
		return "list[" + pyType(object(s["items"]), eager) + "]"
	case "object":
		if additional, ok := s["additionalProperties"]; ok {
			return "dict[str, " + pyType(object(additional), eager) + "]"
		}
		return "dict[str, Any]"
	}
	return "Any"
}
